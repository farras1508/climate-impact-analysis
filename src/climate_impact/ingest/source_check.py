"""Check that every HTTP data source is reachable before ingestion (Phase 2, Step 2.1).

Sends lightweight requests (HEAD, falling back to a 1-byte ranged GET when a server
rejects HEAD) and records status, final URL, size and last-modified date.
Nothing is downloaded and nothing is written to data/.
"""

from __future__ import annotations

import argparse
import logging
import sys
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any

import requests

from climate_impact.config import PROJECT_ROOT, load_datasets

logger = logging.getLogger(__name__)

USER_AGENT = "climate-impact-analysis/0.1 (research; source availability check)"
TIMEOUT_S = 30
MIN_PLAUSIBLE_BYTES = 1024  # a data file this small is almost certainly a stub or error page
QUESTIONS = ("Q1", "Q2", "Q3", "Q4", "Q5")
HEAD_REJECTED = frozenset({403, 405, 501})
PROBLEM_OUTCOMES = frozenset({"failed", "suspect"})


@dataclass(frozen=True)
class SourceStatus:
    """Result of checking one catalogue entry."""

    dataset: str
    priority: str
    access: str
    outcome: str  # one of: ok, suspect, failed, manual
    url: str = ""
    status_code: int | None = None
    final_url: str = ""
    size_bytes: str = ""
    last_modified: str = ""
    note: str = ""


def resolve_url(meta: dict[str, Any]) -> str | None:
    """Return the URL to check for a catalogue entry, or None if it is not HTTP-accessible."""
    if meta.get("access") != "http":
        return None
    if "url" in meta:
        return str(meta["url"])
    if "url_template" in meta and "template_check_value" in meta:
        return str(meta["url_template"]).format(country=meta["template_check_value"])
    return None


def _size_from_headers(headers: Mapping[str, str]) -> str:
    content_range = headers.get("Content-Range", "")
    if "/" in content_range:  # ranged GET: "bytes 0-0/<total>"
        return content_range.rsplit("/", 1)[1]
    return headers.get("Content-Length", "")


def check_source(name: str, meta: dict[str, Any], session: requests.Session) -> SourceStatus:
    """Check one catalogue entry; non-HTTP sources are marked for manual verification.

    A HEAD size below MIN_PLAUSIBLE_BYTES is not trusted on its own (some servers report
    misleading HEAD lengths); it is confirmed with a 1-byte ranged GET before flagging.
    """
    priority = str(meta.get("priority", ""))
    access = str(meta.get("access", ""))
    url = resolve_url(meta)
    if url is None:
        return SourceStatus(name, priority, access, "manual", note="verify access and licence")

    headers = {"User-Agent": USER_AGENT, "Accept-Encoding": "identity"}
    try:
        response = session.head(url, allow_redirects=True, timeout=TIMEOUT_S, headers=headers)
        size = _size_from_headers(response.headers)
        too_small = size.isdigit() and int(size) < MIN_PLAUSIBLE_BYTES
        if response.status_code in HEAD_REJECTED or (response.status_code < 400 and too_small):
            response = session.get(
                url,
                allow_redirects=True,
                timeout=TIMEOUT_S,
                headers={**headers, "Range": "bytes=0-0"},
                stream=True,
            )
            response.close()
            size = _size_from_headers(response.headers)
    except requests.RequestException as exc:
        return SourceStatus(name, priority, access, "failed", url=url, note=type(exc).__name__)

    if response.status_code >= 400:
        outcome, note = "failed", ""
    elif size.isdigit() and int(size) < MIN_PLAUSIBLE_BYTES:
        outcome, note = "suspect", f"only {size} bytes (confirmed by ranged GET)"
    else:
        outcome, note = "ok", ""
    return SourceStatus(
        name,
        priority,
        access,
        outcome,
        url=url,
        status_code=response.status_code,
        final_url=response.url,
        size_bytes=size,
        last_modified=response.headers.get("Last-Modified", ""),
        note=note,
    )


def coverage_matrix(datasets: dict[str, Any]) -> list[str]:
    """Render the dataset-to-question matrix (framework Step 2.2) as Markdown table lines."""
    lines = [
        "| Dataset | Priority | " + " | ".join(QUESTIONS) + " |",
        "|---|---|" + "|".join([":-:"] * len(QUESTIONS)) + "|",
    ]
    for name, meta in sorted(datasets.items()):
        marks = ["●" if q in meta.get("questions", []) else "" for q in QUESTIONS]
        lines.append(f"| {name} | {meta.get('priority', '')} | " + " | ".join(marks) + " |")
    return lines


def render_report(statuses: list[SourceStatus], datasets: dict[str, Any], checked_at: str) -> str:
    """Build the Markdown source-check report."""
    lines = [
        "# Source Check Report",
        "",
        f"Checked at {checked_at} (UTC). Generated by `make check-sources`; do not edit by hand.",
        "",
        "## Reachability",
        "",
        "| Dataset | Priority | Access | Outcome | HTTP | Size (bytes) "
        "| Last-Modified | Note / final URL |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in statuses:
        detail = " — ".join(part for part in (s.note, s.final_url) if part)
        lines.append(
            f"| {s.dataset} | {s.priority} | {s.access} | {s.outcome} | {s.status_code or ''} "
            f"| {s.size_bytes} | {s.last_modified} | {detail} |"
        )
    lines += ["", "## Dataset-to-question coverage (from config/datasets.yaml)", ""]
    lines += coverage_matrix(datasets)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Check all sources, write reports/source_check.md; exit 1 if a core source has a problem."""
    argparse.ArgumentParser(description=__doc__).parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    datasets = load_datasets()
    with requests.Session() as session:
        statuses = [check_source(name, meta, session) for name, meta in sorted(datasets.items())]

    checked_at = datetime.now(UTC).strftime("%Y-%m-%d %H:%M")
    report = PROJECT_ROOT / "reports" / "source_check.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(render_report(statuses, datasets, checked_at), encoding="utf-8", newline="\n")

    for s in statuses:
        log = logger.error if s.outcome in PROBLEM_OUTCOMES else logger.info
        log("%-28s %-7s %s", s.dataset, s.outcome, s.note or s.status_code or "")
    problems = [s for s in statuses if s.outcome in PROBLEM_OUTCOMES and s.priority == "core"]
    logger.info("Report written to %s", report.relative_to(PROJECT_ROOT).as_posix())
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
